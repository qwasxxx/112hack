export function pickInterventionNote(type: InterventionType, custom?: string): string {
  const trimmed = custom?.trim() ?? '';
  if (trimmed) {
    return trimmed;
  }
  const pool = INTERVENTION_PRESETS[type] ?? ['Следуй указанию преподавателя.'];
  return pool[Math.floor(Math.random() * pool.length)] ?? pool[0];
}
